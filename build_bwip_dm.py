"""Build src/bwip_dm.js: a Data Matrix-only bwip-js bundle (MIT, Mark Warren) for the Worker's generate_data_matrix tool.
The full bwip-js is 2+ MB because bwipp_lookup() pulls in every symbology; this keeps only datamatrix + gs1datamatrix
(≈220 KB minified). Needs npm (npm pack) and the esbuild that ships with wrangler. Run: python3 build_bwip_dm.py"""
import re, subprocess, tempfile
from pathlib import Path
VER = "4.11.3"
HERE = Path(__file__).parent
with tempfile.TemporaryDirectory() as d:
    d = Path(d)
    subprocess.run(["npm", "pack", f"bwip-js@{VER}", "-q"], cwd=d, check=True, capture_output=True)
    subprocess.run(["tar", "xzf", f"bwip-js-{VER}.tgz"], cwd=d, check=True)
    gen = d / "package/dist/bwip-js-gen.mjs"
    s = gen.read_text()
    s = re.sub(r"^import \{[^}]*\} from './bwipp.mjs';",
               "import { bwipp_datamatrix, bwipp_gs1datamatrix, bwipp_encode, BWIPP_VERSION } from './bwipp.mjs';\n"
               "function bwipp_lookup(b){ if(b==='datamatrix') return bwipp_datamatrix; if(b==='gs1datamatrix') return bwipp_gs1datamatrix; throw new Error('bwipp.undefinedEncoder: '+b); }\n"
               "const bwipp_symlist=['datamatrix','gs1datamatrix'];", s, count=1, flags=re.M)
    s = re.sub(r"^export function \w+\(opts,dwg\) \{ return _Render\(bwipp_\w+,opts,dwg\); \};\n", "", s, flags=re.M)
    (d / "package/dist/dm-gen.mjs").write_text(s)
    (d / "entry.mjs").write_text("import bwip from './package/dist/dm-gen.mjs';\nexport const bwipDM = { raw: bwip.raw };\n")
    out = d / "out.mjs"
    subprocess.run([str(HERE / "node_modules/.bin/esbuild"), "entry.mjs", "--bundle", "--minify", "--format=esm", f"--outfile={out}"], cwd=d, check=True, capture_output=True)
    lic = (d / "package/LICENSE").read_text().strip()
    head = f"// GENERATED by build_bwip_dm.py from bwip-js@{VER} (Data Matrix encoders only) — do not edit by hand.\n/*\n{lic}\n*/\n"
    (HERE / "src/bwip_dm.js").write_text(head + out.read_text())
print("wrote src/bwip_dm.js", (HERE / "src/bwip_dm.js").stat().st_size)
