"""Generate src/tools_core.js (ES module for the Worker) from the browser cores of the batch-43 tools —
one source of truth with /tools/font-generator/, /tools/character-counter/, /tools/diff-checker/,
/tools/color-combination-generator/, /tools/upc-generator/, /tools/flowchart-maker/ + /tools/mind-map-maker/,
/tools/logo-maker/ and /tools/passport-photo-maker/.
Also generates src/tools_core44.js from the batch-44 cores (puzzles, usernames, Gantt, calendar holidays,
weekly schedule, timeline, org chart, Venn, pie chart) and src/tools_core45.js from the batch-45 cores (Data Matrix,
swatches, graphs, subtitles, image resize maths, text case). src/bwip_dm.js is built separately by build_bwip_dm.py.
Run after editing any of these files in tool-gap-2026-10/newtools/, then deploy."""
from pathlib import Path
NT = Path.home() / "Downloads/EtiennAubertBonn/tool-gap-2026-10/newtools"
FILES = ["unicode-fonts-core.js", "charcount-core.js", "diff-core.js", "combos-core.js", "upc-core.js",
         "diagram-core.js", "logo-data.js", "logo-core.js", "passport-core.js"]
TAILS = ["})(typeof window !== 'undefined' ? window : globalThis);", '})(typeof window !== "undefined" ? window : globalThis);']
def bundle(files):
    parts = []
    for f in files:
        s = (NT / f).read_text().rstrip()
        tail = next((t for t in TAILS if s.endswith(t)), None)
        assert tail, f
        parts.append(s[: -len(tail)] + "})(G);")
    return parts
parts = []
for f in FILES:
    s = (NT / f).read_text().rstrip()
    tail = next((t for t in TAILS if s.endswith(t)), None)
    assert tail, f
    parts.append(s[: -len(tail)] + "})(G);")
out = ("// GENERATED by gen_tools_core.py from tool-gap-2026-10/newtools/{" + ",".join(FILES) + "} — do not edit by hand.\n"
       'import { MGDRoles } from "./design_core.js";\n'
       "const G = { MGDRoles };\n" + "\n".join(parts) + "\n" +
       "".join(f"export const {k} = G.{k};\n" for k in ["MGDUnicodeFonts", "MGDCharCount", "MGDDiff", "MGDCombos", "MGDUpc", "MGDDiagram", "MGDLogo", "MGDPassport"]))
Path(__file__).with_name("src").joinpath("tools_core.js").write_text(out)
print("wrote src/tools_core.js", len(out))

