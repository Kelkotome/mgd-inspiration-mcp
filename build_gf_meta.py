#!/usr/bin/env python3
"""build_gf_meta.py (16-Nov-2026, fonts r4): src/gf_meta.js = every Google Fonts family with its category, stroke, primary script and
popularity rank, for get_font_pairing's "similar fonts" fallback (a Google Font with no guide and no partner hits gets the published
pairings of the closest guide fonts instead of an empty answer). Offline; the input is a saved copy of https://fonts.google.com/metadata/fonts.

  python3 -I build_gf_meta.py METADATA_FONTS_JSON [OUT=src/gf_meta.js]

One line per family: Family|category|stroke|script|popularity. Codes: S Sans Serif, R Serif, D Display, H Handwriting, M Monospace
(stroke uses the same codes; empty when Google Fonts gives none). script = Google Fonts primaryScript (empty = Latin-first).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(sys.argv[1], encoding="utf-8").read()
data = json.loads(src[src.index("{"):])
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "src", "gf_meta.js")
CODE = {"Sans Serif": "S", "Serif": "R", "Display": "D", "Handwriting": "H", "Monospace": "M"}
rows = []
for f in sorted(data["familyMetadataList"], key=lambda x: x["family"]):
    fam = f["family"]
    assert "|" not in fam and "\n" not in fam, fam
    rows.append("|".join([fam, CODE[f["category"]], CODE.get(f.get("stroke") or "", ""), f.get("primaryScript") or "", str(int(f.get("popularity") or 9999))]))
body = "\n".join(rows)
with open(OUT, "w", encoding="utf-8") as o:
    o.write("// GENERATED by build_gf_meta.py (fonts r4, 16-Nov-2026) from fonts.google.com/metadata/fonts. Do not edit by hand.\n")
    o.write(f"// {len(rows)} families: Family|category|stroke|primaryScript|popularity (S sans, R serif, D display, H handwriting, M mono).\n")
    o.write("export const GF_META = " + json.dumps(body, ensure_ascii=False) + ";\n")
print(f"{len(rows)} families -> {OUT} ({os.path.getsize(OUT) // 1024} KB)")
