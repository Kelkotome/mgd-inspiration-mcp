"""Generate src/design_core.js (ES module for the Worker) from the browser cores used by
/tools/website-color-palette-generator/ and /tools/design-md-generator/ — one source of truth.
Run after editing tool-gap-2026-10/newtools/{color-roles-core.js,design-md-core.js}, then deploy."""
from pathlib import Path
NT = Path.home() / "Downloads/EtiennAubertBonn/tool-gap-2026-10/newtools"
parts = []
for f in ("color-roles-core.js", "design-md-core.js"):
    s = (NT / f).read_text().rstrip()
    assert s.endswith("})(window);"), f
    parts.append(s[: -len("})(window);")] + "})(G);")
out = ("// GENERATED by gen_design_core.py from tool-gap-2026-10/newtools/color-roles-core.js + design-md-core.js — do not edit by hand.\n"
       "const G = {};\n" + "\n".join(parts) + "\nexport const MGDRoles = G.MGDRoles;\nexport const MGDDesignMd = G.MGDDesignMd;\n")
assert "window" not in out.replace("(window)", "")
Path(__file__).with_name("src").joinpath("design_core.js").write_text(out)
print("wrote src/design_core.js", len(out))
